// 这是**随包发布的内置公告**：服务端没有保存过公告时（全新安装、文件丢了、文件坏了），玩家看到的就是这一份。
// 运维在 `/admin/` 面板里保存过之后，服务端那份就赢过这份，客户端启动时会去 `GET /api/notes` 取。
//
// ============================ 怎么改（就两步）============================
//
//   1. 直接改下面 `BUILTIN_TEXT` 里的**文字**。它是**自由文本**——想怎么写就怎么写，不需要任何格式：
//        * 空行 = 分段（面板按段落渲染）；
//        * 以 `- ` 或 `* ` 开头的行 = 分条（面板渲染成项目符号列表）；
//        * 其余行原样显示，行尾换行保留。
//      没有 version、没有 date、没有 headline、没有 sections，**也没有多语言**：你写什么语言，玩家就看什么语言。
//   2. 跑 `npm run update-notes` 自检（= `node tools/update-notes.mjs`）：查空公告、超长（上限
//      `NOTES_LIMITS.text` = 4000 字）、控制字符；`-- --digest` 会打印这份公告的指纹。
//
// ============================ 唯一的机关 ================================
//
//   改文字就是「解锁」的全部机关：`updateNotesDigest()`（ui/updateNotesModel.js）把 `{ text }` 用
//   canonicalJson + sha256Hex 算出指纹，和玩家浏览器里存的上次关闭时的指纹比对。**这里任何改动**都会让指纹变，
//   于是每位玩家下次进来就再看到一次面板。反过来说：光把别处的版本号往上挪、这里没动，就【不会】弹
//   （没有新东西可说，不该打扰玩家）。所以**忘改版本号绝不会让玩家漏看公告——内容本身就是身份**。
//
//   文本在这里先过一遍 `sanitizeNotesText()`，所以这份内置公告与「运维在面板里存下同一段文字」算出的指纹
//   完全相同（行尾空格、CRLF、多余空行都不会让两者分叉）。

